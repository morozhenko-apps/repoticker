export function normalizeLocale(value) {
  return LOCALE_ROSTER.some(locale => locale.code === value) ? value : "en";
}
export function localeName(value) {
  return LOCALE_ROSTER.find(locale => locale.code === value)?.name ?? "English";
}
export function localeDirection(value) {
  return normalizeLocale(value) === "ar" ? "rtl" : "ltr";
}
export function coreText(value, english) {
  if (typeof english !== "string") throw new Error("Invalid translation key");
  return CORE_TERMS[normalizeLocale(value)]?.[english] ?? english;
}
