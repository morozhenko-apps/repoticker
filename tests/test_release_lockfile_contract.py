"""Pinned Cargo.lock must govern every stable Rust CI gate."""
import pathlib
import unittest

ROOT = pathlib.Path(__file__).resolve().parents[1]


class CargoLockfileContract(unittest.TestCase):
    def test_workspace_lockfile_is_tracked_policy_not_ignored(self):
        lockfile = ROOT / "Cargo.lock"
        self.assertTrue(lockfile.is_file())
        contents = lockfile.read_text(encoding="utf-8")
        self.assertIn("This file is automatically @generated by Cargo", contents)
        self.assertIn("version = 4", contents)
        ignored = (ROOT / ".gitignore").read_text(encoding="utf-8")
        self.assertIn("Application workspace lockfile is committed", ignored)
        self.assertNotIn("\nCargo.lock\n", ignored)

    def test_all_cargo_quality_gates_refuse_implicit_resolution(self):
        preflight = (ROOT / ".github/workflows/preflight.yml").read_text(encoding="utf-8")
        strict = (ROOT / ".github/workflows/strict.yml").read_text(encoding="utf-8")
        release = (ROOT / ".github/workflows/desktop-release-candidates.yml").read_text(encoding="utf-8")
        for command in [
            "cargo test --locked -p repoticker-core",
            "cargo clippy --locked -p repoticker-core --all-targets -- -D warnings",
            "cargo check --locked -p repoticker-desktop",
        ]:
            self.assertIn(command, preflight)
        self.assertIn("cargo test --locked -p repoticker-core", strict)
        self.assertIn("cargo metadata --locked", release)


if __name__ == "__main__":
    unittest.main()
